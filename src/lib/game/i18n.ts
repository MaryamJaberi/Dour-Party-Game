function interpolate(s: string, vars?: Record<string, string | number>) {
  if (!vars) return s;
  return s.replace(/\{(\w+)\}/g, (_, k) => String(vars[k] ?? ""));
}

export function t(lang: Language, key: string, vars?: Record<string, string | number>): string {
  const pack = EXTRA[lang] || EXTRA[lang === "en-US" ? "en" : lang] || EXTRA.en;
  if (pack[key]) return interpolate(pack[key], vars);
  const dict = (TRANSLATIONS[lang] || TRANSLATIONS.en) as Record<string, unknown>;
  const val = dict[key];
  if (typeof val === "string") return interpolate(val, vars);
  return interpolate(EXTRA.en[key] || key, vars);
}

export function tCat(lang: Language, id: string): string {
  const dict = (TRANSLATIONS[lang] || TRANSLATIONS.en) as {
    categories?: Record<string, string>;
  };
  return dict.categories?.[id] || (TRANSLATIONS.en as { categories: Record<string, string> }).categories[id] || id;
}

export function tTeam(lang: Language, color: string): string {
  const dict = (TRANSLATIONS[lang] || TRANSLATIONS.en) as {
    teamNames?: Record<string, string>;
  };
  return dict.teamNames?.[color] || color;
}

